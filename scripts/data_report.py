"""
data_report.py

Writes data_report.md: what data is installed, station coverage per year,
the results of the data checks and the station list status. Covers every
year folder present, not only the years the app is configured to use.

The idea of a written data report follows data_report.md in the aitraffic
project (github.com/DanieMyl/aitraffic); this version is generated from
this project's own loader and checks.

Usage:
    python scripts/data_report.py            # writes data_report.md
    python scripts/data_report.py --stdout   # prints instead
"""

import argparse
import datetime
import os
import sys

PROJECT_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, PROJECT_DIR)
from data_utils import (BASE_DIR, check_data, configured_years, load_coordinates,  # noqa: E402
                        load_traffic_data, year_status)


def build_report():
    status = year_status(BASE_DIR)
    df = load_traffic_data(base_path=BASE_DIR, years=status['present'])
    coords = load_coordinates(BASE_DIR)
    issues, per = check_data(df)
    years = sorted(int(y) for y in df['year'].unique())
    used = configured_years()

    lines = [
        "# Data report",
        "",
        f"Generated by `scripts/data_report.py` on {datetime.date.today():%Y-%m-%d}.",
        "",
        "## Installed data",
        "",
        f"- Year folders present: {', '.join(map(str, status['present']))}",
        f"- Years the app uses (A3_YEARS): {', '.join(map(str, used)) if used else 'all'}"
        f" -> in use: {', '.join(map(str, status['used'])) or 'none'}"
        + (f"; missing: {', '.join(map(str, status['missing']))}" if status['missing'] else ""),
        f"- Hourly rows: {len(df):,} ({df['Datum'].min():%Y-%m-%d} to {df['Datum'].max():%Y-%m-%d})",
        f"- Station list: {coords.attrs.get('source_file')} — {len(coords)} A3 stations in Bavaria; "
        f"names: {(coords['name_status'] == 'ok').sum()} intact, {(coords['name_status'] == 'repaired').sum()} "
        f"repaired, {(coords['name_status'] == 'damaged').sum()} still damaged",
        "",
        "## Stations per year",
        "",
        "| Year | Stations | Hourly rows |",
        "|---|---:|---:|",
    ]
    for y in years:
        part = df[df['year'] == y]
        lines.append(f"| {y} | {part['Zst'].nunique()} | {len(part):,} |")

    names = dict(zip(coords['DZ_Nr'], coords['DZ_Name']))
    lines += ["", "## Coverage by station", "",
              "| Station | Name | " + " | ".join(map(str, years)) + " |",
              "|---|---|" + "|".join([":-:"] * len(years)) + "|"]
    have = set(zip(df['Zst'], df['year']))
    for nr in sorted(set(coords['DZ_Nr']) | set(df['Zst'])):
        cells = ["yes" if (nr, y) in have else "" for y in years]
        lines.append(f"| {nr} | {names.get(nr, '(not in station list)')} | " + " | ".join(cells) + " |")

    lines += ["", "## Data checks", ""]
    lines += [f"- {i}" for i in issues] or ["- No findings."]
    lines += ["", "Checked: hours per station and year (8,760, or 8,784 in leap years), duplicate and "
              "missing hours, empty, negative and impossible counts (over 10,000 vehicles per hour in "
              "one direction), more trucks than vehicles, BASt quality flags.", "",
              "## Share of estimated counts (BASt flag 's')", "",
              "| Station | " + " | ".join(map(str, years)) + " |",
              "|---|" + "|".join(["---:"] * len(years)) + "|"]
    table = per.pivot(index='station', columns='year', values='estimated_share')
    for nr, row in table.iterrows():
        cells = ["" if row.get(y) != row.get(y) or y not in row else f"{row[y]:.0%}" for y in years]
        lines.append(f"| {nr} | " + " | ".join(cells) + " |")
    lines += ["", "Share of hourly counts in both directions that BASt marked as estimated. A high share "
              "means the averages for that station rely more on BASt's estimates than on counted values. "
              "The flag meanings ('s' estimated, 'u' implausible) are taken from the aitraffic project's "
              "data report and have not been checked against the BASt documentation."]
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description="Write data_report.md for the installed data.")
    parser.add_argument('--stdout', action='store_true')
    args = parser.parse_args()
    try:
        report = build_report()
    except FileNotFoundError as e:
        print(f"ERROR: {e}\nRun scripts/fetch_data.py first.")
        return 1
    if args.stdout:
        print(report)
    else:
        path = os.path.join(PROJECT_DIR, 'data_report.md')
        with open(path, 'w', encoding='utf-8') as f:
            f.write(report)
        print(f"Wrote {path}")
    return 0


if __name__ == '__main__':
    sys.exit(main())
